// Generates lib/core/design_system/tokens/mu_tokens.g.dart from
// design/tokens.json (the μLearn Mobile design system's tokens).
//
//   dart run tool/gen_tokens.dart
//
// test/tool/gen_tokens_test.dart fails when the committed file is stale.
import 'dart:convert';
import 'dart:io';

const tokensPath = 'design/tokens.json';
const outputPath = 'lib/core/design_system/tokens/mu_tokens.g.dart';

void main() {
  final json = jsonDecode(File(tokensPath).readAsStringSync()) as Map<String, dynamic>;
  File(outputPath)
    ..createSync(recursive: true)
    ..writeAsStringSync(generateTokens(json));
  stdout.writeln('wrote $outputPath');
}

/// Returns the Dart source of `mu_tokens.g.dart` for a parsed tokens.json.
String generateTokens(Map<String, dynamic> json) {
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/gen_tokens.dart from $tokensPath. Do not edit.')
    ..writeln('// ignore_for_file: public_member_api_docs, lines_longer_than_80_chars')
    ..writeln()
    ..writeln("import 'package:flutter/painting.dart';")
    ..writeln();
  _palette(out, json['color'] as Map<String, dynamic>);
  _type(out, json['type'] as Map<String, dynamic>);
  _lengths(out, 'MuSpacing', 'Spacing (logical px).', json['spacing'], '');
  _lengths(out, 'MuRadii', 'Corner radii (logical px).', json['radius'], 'radius-');
  _lengths(out, 'MuSizes', 'Component dimensions (logical px).', json['size'], '');
  _lengths(out, 'MuOpacity', 'Opacities.', json['opacity'], 'opacity-');
  _shadows(out, json['shadow'] as Map<String, dynamic>);
  _springs(out, json['spring'] as Map<String, dynamic>);
  return out.toString();
}

List<Map<String, dynamic>> _tokens(Object? family) =>
    ((family! as Map<String, dynamic>)['tokens'] as List).cast<Map<String, dynamic>>();

/// `on-night-2` → `onNight2`, `space-0-5` → `space0p5`.
String camel(String name, {String strip = ''}) {
  final base = name.startsWith(strip) ? name.substring(strip.length) : name;
  final parts = base.split(RegExp('[-_.]')).where((p) => p.isNotEmpty).toList();
  final b = StringBuffer(parts.first);
  for (var i = 1; i < parts.length; i++) {
    final p = parts[i];
    final prevNumeric = RegExp(r'^\d+$').hasMatch(parts[i - 1]);
    if (prevNumeric && RegExp(r'^\d+$').hasMatch(p)) {
      b.write('p$p');
    } else {
      b.write(p[0].toUpperCase() + p.substring(1));
    }
  }
  final s = b.toString();
  return RegExp(r'^\d').hasMatch(s) ? 'v$s' : s;
}

String colorLiteral(String css) {
  final v = css.trim().toLowerCase();
  if (v.startsWith('#')) {
    var hex = v.substring(1);
    if (hex.length == 3 || hex.length == 4) hex = hex.split('').map((c) => '$c$c').join();
    final rgb = hex.substring(0, 6);
    final a = hex.length == 8 ? hex.substring(6) : 'ff';
    return 'Color(0x${a.toUpperCase()}${rgb.toUpperCase()})';
  }
  final m = RegExp(r'rgba?\(([^)]+)\)').firstMatch(v);
  if (m == null) throw FormatException('Unsupported colour: $css');
  final n = m.group(1)!.split(',').map((s) => double.parse(s.trim())).toList();
  final a = n.length > 3 ? (n[3] * 255).round() : 255;
  String h(num x) => x.round().toRadixString(16).padLeft(2, '0').toUpperCase();
  return 'Color(0x${h(a)}${h(n[0])}${h(n[1])}${h(n[2])})';
}

void _palette(StringBuffer out, Map<String, dynamic> color) {
  final themes = (color['themes'] as List).map((t) => (t as Map)['id'] as String).toList();
  final tokens = _tokens(color);
  String valueFor(Map<String, dynamic> t, String theme) {
    final v = t['value'];
    if (v is String) return v;
    final m = v as Map<String, dynamic>;
    return (m[theme] ?? m[themes.first]) as String;
  }

  out
    ..writeln('/// Colour tokens. One instance per theme; read through `context.mu.colors`.')
    ..writeln('class MuPalette {')
    ..writeln('  const MuPalette({');
  for (final t in tokens) {
    out.writeln('    required this.${camel(t['name'] as String)},');
  }
  out
    ..writeln('  });')
    ..writeln();
  for (final theme in themes) {
    out.writeln('  static const $theme = MuPalette(');
    for (final t in tokens) {
      out.writeln('    ${camel(t['name'] as String)}: ${colorLiteral(valueFor(t, theme))},');
    }
    out
      ..writeln('  );')
      ..writeln();
  }
  for (final t in tokens) {
    final usage = (t['usage'] as String?)?.replaceAll('\n', ' ');
    if (usage != null) out.writeln('  /// ${usage.replaceAll('`', "'")}');
    out.writeln('  final Color ${camel(t['name'] as String)};');
  }
  out
    ..writeln()
    ..writeln('  MuPalette lerp(MuPalette other, double t) => MuPalette(');
  for (final t in tokens) {
    final n = camel(t['name'] as String);
    out.writeln('    $n: Color.lerp($n, other.$n, t)!,');
  }
  out
    ..writeln('  );')
    ..writeln('}')
    ..writeln();
}

double _px(Object? v, {double size = 0}) {
  if (v is num) return v.toDouble();
  final s = (v! as String).trim();
  if (s.endsWith('px')) return double.parse(s.substring(0, s.length - 2));
  if (s.endsWith('em')) return double.parse(s.substring(0, s.length - 2)) * size;
  return double.parse(s);
}

String _num(double v) {
  final r = (v * 1000).round() / 1000;
  return r == r.roundToDouble() ? r.toStringAsFixed(0) : r.toString();
}

void _type(StringBuffer out, Map<String, dynamic> type) {
  final families = (type['families'] as Map<String, dynamic>).map(
    (k, v) => MapEntry(k, RegExp(r'^\s*"?([^",]+)"?').firstMatch(v as String)!.group(1)!.trim()),
  );
  out
    ..writeln('/// Font families. Resolved to TextStyles by the theme (google_fonts).')
    ..writeln('enum MuFontFamily {');
  for (final e in families.entries) {
    out.writeln("  ${camel(e.key)}('${e.value}'),");
  }
  out
    ..writeln('  ;')
    ..writeln()
    ..writeln('  const MuFontFamily(this.familyName);')
    ..writeln('  final String familyName;')
    ..writeln('}')
    ..writeln()
    ..writeln('/// One type style: size, leading (multiplier), weight, tracking (px).')
    ..writeln('class MuTypeSpec {')
    ..writeln(
      '  const MuTypeSpec({required this.family, required this.size, required this.height, required this.weight, this.letterSpacing = 0});',
    )
    ..writeln('  final MuFontFamily family;')
    ..writeln('  final double size;')
    ..writeln('  final double height;')
    ..writeln('  final int weight;')
    ..writeln('  final double letterSpacing;')
    ..writeln('}')
    ..writeln()
    ..writeln('/// The type scale.')
    ..writeln('abstract final class MuTypeTokens {');
  for (final g in (type['groups'] as List).cast<Map<String, dynamic>>()) {
    for (final s in (g['styles'] as List).cast<Map<String, dynamic>>()) {
      final size = _px(s['fontSize']);
      final lhRaw = s['lineHeight'];
      final height = lhRaw is String && lhRaw.endsWith('px') ? _px(lhRaw) / size : _px(lhRaw);
      final tracking = s['letterSpacing'] == null ? 0.0 : _px(s['letterSpacing'], size: size);
      final family = camel((s['family'] ?? g['family']) as String);
      final usage = (s['usage'] as String?)?.replaceAll('`', "'");
      if (usage != null) out.writeln('  /// $usage');
      out.writeln(
        '  static const ${camel(s['name'] as String)} = MuTypeSpec(family: MuFontFamily.$family, '
        'size: ${_num(size)}, height: ${_num(height)}, weight: ${s['fontWeight']}, letterSpacing: ${_num(tracking)});',
      );
    }
  }
  out
    ..writeln('}')
    ..writeln();
}

void _lengths(StringBuffer out, String cls, String doc, Object? family, String strip) {
  out
    ..writeln('/// $doc')
    ..writeln('abstract final class $cls {');
  for (final t in _tokens(family)) {
    final usage = (t['usage'] as String?)?.replaceAll('`', "'");
    if (usage != null) out.writeln('  /// $usage');
    out.writeln('  static const double ${camel(t['name'] as String, strip: strip)} = ${_num(_px(t['value']))};');
  }
  out
    ..writeln('}')
    ..writeln();
}

String _shadowList(String css) {
  final layers = css.split(RegExp(r',(?![^(]*\))'));
  final items = layers.map((layer) {
    final colour = RegExp(r'rgba?\([^)]+\)|#[0-9a-fA-F]+').firstMatch(layer)!.group(0)!;
    final nums = layer.replaceAll(colour, '').trim().split(RegExp(r'\s+')).map(_px).toList();
    final spread = nums.length > 3 ? nums[3] : 0.0;
    return 'BoxShadow(color: ${colorLiteral(colour)}, offset: Offset(${_num(nums[0])}, ${_num(nums[1])}), '
        'blurRadius: ${_num(nums[2])}, spreadRadius: ${_num(spread)})';
  });
  return '[${items.join(', ')}]';
}

void _shadows(StringBuffer out, Map<String, dynamic> shadow) {
  final tokens = _tokens(shadow);
  out
    ..writeln('/// Elevation. Shadows mean "this floats"; content cards never cast one.')
    ..writeln('class MuShadows {')
    ..writeln(
      '  const MuShadows({${tokens.map((t) => 'required this.${camel(t['name'] as String, strip: 'shadow-')}').join(', ')}});',
    )
    ..writeln();
  for (final theme in ['light', 'dark']) {
    out.writeln('  static const $theme = MuShadows(');
    for (final t in tokens) {
      final v = t['value'];
      final css = v is String ? v : (v as Map<String, dynamic>)[theme] as String;
      out.writeln('    ${camel(t['name'] as String, strip: 'shadow-')}: ${_shadowList(css)},');
    }
    out.writeln('  );');
  }
  for (final t in tokens) {
    out.writeln('  final List<BoxShadow> ${camel(t['name'] as String, strip: 'shadow-')};');
  }
  out
    ..writeln('}')
    ..writeln();
}

void _springs(StringBuffer out, Map<String, dynamic> spring) {
  out
    ..writeln('/// Apple-style spring: damping ratio and response (s). See motion/mu_spring.dart.')
    ..writeln('class MuSpringSpec {')
    ..writeln('  const MuSpringSpec({required this.damping, required this.response});')
    ..writeln('  final double damping;')
    ..writeln('  final double response;')
    ..writeln('}')
    ..writeln()
    ..writeln('/// The spring set.')
    ..writeln('abstract final class MuSprings {');
  for (final t in _tokens(spring)) {
    final m = RegExp(r'damping ([\d.]+) response ([\d.]+)s').firstMatch(t['value'] as String)!;
    final usage = (t['usage'] as String?)?.replaceAll('`', "'");
    if (usage != null) out.writeln('  /// $usage');
    out.writeln(
      '  static const ${camel(t['name'] as String, strip: 'spring-')} = '
      'MuSpringSpec(damping: ${m.group(1)}, response: ${m.group(2)});',
    );
  }
  out.writeln('}');
}
